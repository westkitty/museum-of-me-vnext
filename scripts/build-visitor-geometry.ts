// Generates src/world/visitorGeometry.generated.ts: the 78 composed visitor
// geometries, byte for byte, from the authored records via the real composer.
// Deterministic: running it twice yields identical output. Run by
// `npm run build:collection` (so dev, build and the gate always regenerate it).
import { writeFileSync } from 'node:fs';
import { SOURCE_VISITORS } from '../src/content/sourceParity';
import { createVisitorGeometry } from '../src/world/VisitorVisuals';

const geometries = createVisitorGeometry(SOURCE_VISITORS);
const keys = Object.keys(geometries);
let vertices = 0;
let indices = 0;
for (const key of keys) {
  vertices += geometries[key].getAttribute('position').count;
  indices += geometries[key].getIndex()!.count;
}
const bytes = new Uint8Array(vertices * 44 + indices * 2);
const f32 = new Float32Array(bytes.buffer, 0, vertices * 11);
const index = new Uint16Array(bytes.buffer, vertices * 44, indices);
const entries: Array<[string, number, number, number, number, number[]]> = [];
let v = 0;
let i = 0;
for (const key of keys) {
  const g = geometries[key];
  const count = g.getAttribute('position').count;
  const indexCount = g.getIndex()!.count;
  f32.set(g.getAttribute('position').array as Float32Array, v * 3);
  f32.set(g.getAttribute('normal').array as Float32Array, vertices * 3 + v * 3);
  f32.set(g.getAttribute('uv').array as Float32Array, vertices * 6 + v * 2);
  f32.set(g.getAttribute('color').array as Float32Array, vertices * 8 + v * 3);
  index.set(g.getIndex()!.array as Uint16Array, i);
  g.computeBoundingBox();
  g.computeBoundingSphere();
  const { min, max } = g.boundingBox!;
  const { center, radius } = g.boundingSphere!;
  entries.push([key, v, count, i, indexCount, [min.x, min.y, min.z, max.x, max.y, max.z, center.x, center.y, center.z, radius]]);
  v += count;
  i += indexCount;
  g.dispose();
}
const source = `// @generated by scripts/build-visitor-geometry.ts from the authored visitor records. Do not edit.
// Layout: position, normal, uv, color (Float32, all vertices) then index (Uint16, all indices).
// Entry: [key, firstVertex, vertexCount, firstIndex, indexCount, [bbox min xyz, bbox max xyz, sphere center xyz, radius]].
export const VISITOR_GEOMETRY_LAYOUT = ${JSON.stringify({ vertices, indices, entries })} as unknown as {
  readonly vertices: number;
  readonly indices: number;
  readonly entries: ReadonlyArray<readonly [string, number, number, number, number, readonly number[]]>;
};
export const VISITOR_GEOMETRY_BASE64 = '${Buffer.from(bytes).toString('base64')}';
`;
writeFileSync('src/world/visitorGeometry.generated.ts', source);
console.log(`visitor geometry: ${keys.length} geometries, ${vertices} vertices, ${indices} indices, ${(bytes.length / 1024).toFixed(0)} KB`);
