#!/usr/bin/env node
// Regenerate the facts block of docs/STATUS.md from primary sources:
// the remote branches, GitHub Actions, open pull requests and the hosted
// build-info.json. Needs network access and an authenticated `gh`.
// Usage: npm run status            (rewrite the block)
//        npm run status -- --check (print only; exit 1 if the block is stale)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const FILE = 'docs/STATUS.md';
const BEGIN = '<!-- status:begin (generated by `npm run status`; do not edit by hand) -->';
const END = '<!-- status:end -->';
const PAGES_BUILD_INFO = 'https://westkitty.github.io/museum-of-me-vnext/build-info.json';

const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8' }).trim();
const short = (sha) => (sha ? sha.slice(0, 7) : 'unknown');

function remoteHead(branch) {
  const line = run('git', ['ls-remote', 'origin', `refs/heads/${branch}`]);
  return line.split(/\s+/)[0] || null;
}

function latestRun(workflow, branch) {
  const [latest] = JSON.parse(run('gh', ['run', 'list', '--workflow', workflow, '--branch', branch, '--limit', '1',
    '--json', 'databaseId,headSha,status,conclusion,createdAt,url']));
  return latest ?? null;
}

async function hostedBuild() {
  try {
    const response = await fetch(PAGES_BUILD_INFO, { cache: 'no-store' });
    if (!response.ok) return { error: `HTTP ${response.status}` };
    return await response.json();
  } catch (error) {
    return { error: String(error) };
  }
}

const describeRun = (r) => (r ? `${r.conclusion || r.status} on \`${short(r.headSha)}\` ([run ${r.databaseId}](${r.url}), ${r.createdAt})` : 'no runs found');

const main = remoteHead('main');
const pages = remoteHead('pages-preview');
const ci = latestRun('ci.yml', 'main');
const deploy = latestRun('deploy-pages.yml', 'pages-preview');
const hosted = await hostedBuild();
const hostedSha = hosted.commit ?? hosted.sha ?? hosted.gitSha ?? null;
const prs = JSON.parse(run('gh', ['pr', 'list', '--state', 'open', '--json', 'number,title,headRefName,isDraft']));
let mainContainsPages = 'unknown';
try {
  run('git', ['fetch', '--quiet', 'origin', 'main', 'pages-preview']);
  execFileSync('git', ['merge-base', '--is-ancestor', pages, main]);
  mainContainsPages = 'yes';
} catch {
  mainContainsPages = 'no';
}

const lines = [
  BEGIN,
  '',
  '| Fact | Value |',
  '|---|---|',
  `| \`main\` | \`${short(main)}\` |`,
  `| Latest CI on \`main\` | ${describeRun(ci)} |`,
  `| \`pages-preview\` | \`${short(pages)}\` (ancestor of \`main\`: ${mainContainsPages}) |`,
  `| Latest Pages deploy | ${describeRun(deploy)} |`,
  `| Hosted build | ${hostedSha ? `\`${short(hostedSha)}\`` : `unreadable (${hosted.error ?? 'no commit field'})`} at ${PAGES_BUILD_INFO.replace('/build-info.json', '/')} |`,
  `| Open pull requests | ${prs.length ? prs.map((pr) => `#${pr.number} ${pr.isDraft ? '(draft) ' : ''}${pr.title}`).join('; ') : 'none'} |`,
  '',
  END,
];
const block = lines.join('\n');
const current = readFileSync(FILE, 'utf8');
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
if (start < 0 || stop < start) throw new Error(`${FILE} is missing its status markers`);
const next = current.slice(0, start) + block + current.slice(stop + END.length);

if (process.argv.includes('--check')) {
  console.log(block);
  // Generated at a moment in time; differences mean the record is out of date, not wrong.
  process.exit(next === current ? 0 : 1);
}
writeFileSync(FILE, next);
console.log(block);
